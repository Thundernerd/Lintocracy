import type { OptionTally, Rule, RuleTally } from '#shared/types/rule'

export interface GenerateOptions {
  /** Include rules that received no votes (emitted as `severity = none`). */
  includeUnvoted?: boolean
  /**
   * Fill in Microsoft's documented defaults (severity + option values) for
   * anything the group hasn't voted on. Implies including unvoted rules.
   */
  useMsDefaults?: boolean
  /** Group votes on configurable option values. */
  optionTallies?: OptionTally[]
  /**
   * ISO timestamp written to the `# Generated` header line. Defaults to now.
   * Pass a fixed value when the text must render identically on server and
   * client (SSR hydration).
   */
  generatedAt?: string
}

const CATEGORY_LABELS: Record<Rule['category'], string> = {
  style: 'Code style rules (IDE)',
  quality: 'Code quality rules (CA)',
}

interface RuleEntry {
  rule: Rule
  severity: string
}

/** Renders one rule's option lines + severity line into `lines`. */
function renderRule(
  lines: string[],
  rule: Rule,
  severity: string,
  useMsDefaults: boolean,
  optionConsensus: Map<string, string>,
) {
  lines.push('')
  lines.push(`# ${rule.id}: ${rule.title}`)
  lines.push(`# ${rule.docsUrl}`)

  if (severity !== 'none') {
    // Precedence: group vote > curated recommendation > MS default.
    const optionLines = new Map<string, string>()
    if (useMsDefaults) {
      for (const opt of rule.options ?? []) {
        if (opt.defaultValue) optionLines.set(opt.name, opt.defaultValue)
      }
    }
    for (const opt of rule.editorconfig.options ?? []) optionLines.set(opt.key, opt.value)
    for (const opt of rule.options ?? []) {
      const value = optionConsensus.get(`${rule.id}::${opt.name}`)
      if (value) optionLines.set(opt.name, value)
    }
    for (const [key, value] of optionLines) lines.push(`${key} = ${value}`)
  }

  lines.push(`dotnet_diagnostic.${rule.editorconfig.diagnosticId}.severity = ${severity}`)
}

/** Emits the given rules grouped by category, under the supplied heading style. */
function emitByCategory(
  lines: string[],
  entries: RuleEntry[],
  heading: (label: string) => string,
  useMsDefaults: boolean,
  optionConsensus: Map<string, string>,
) {
  for (const category of ['style', 'quality'] as const) {
    const inCategory = entries.filter((e) => e.rule.category === category)
    if (!inCategory.length) continue
    lines.push('')
    lines.push(heading(CATEGORY_LABELS[category]))
    for (const { rule, severity } of inCategory) {
      renderRule(lines, rule, severity, useMsDefaults, optionConsensus)
    }
  }
}

/**
 * Generates the text of an `.editorconfig` from the group consensus.
 *
 * For each enabled rule we emit its preferred option value(s) plus a
 * `dotnet_diagnostic.<id>.severity` line. Disabled rules (majority "no") are
 * emitted with `severity = none` so the choice is explicit. When
 * `useMsDefaults` is set, rules and options without a group vote fall back
 * to Microsoft's documented defaults instead of being omitted/`none`.
 */
export function generateEditorConfig(
  rules: Rule[],
  tallies: RuleTally[],
  options: GenerateOptions = {},
): string {
  const {
    includeUnvoted = false,
    useMsDefaults = false,
    generatedAt = new Date().toISOString(),
  } = options
  const tallyById = new Map(tallies.map((t) => [t.ruleId, t]))
  const optionConsensus = new Map<string, string>()
  for (const t of options.optionTallies ?? []) {
    if (t.consensusValue) optionConsensus.set(`${t.ruleId}::${t.optionName}`, t.consensusValue)
  }
  const lines: string[] = []

  lines.push('# .editorconfig generated by Lintocracy — group consensus')
  lines.push(`# Generated ${generatedAt}`)
  if (useMsDefaults) {
    lines.push('# Unvoted rules/options use the Microsoft documented defaults.')
  }
  lines.push('root = true')
  lines.push('')
  lines.push('[*.cs]')

  const entries: { entry: RuleEntry; hasVotes: boolean }[] = []
  for (const rule of rules) {
    const tally = tallyById.get(rule.id)
    const hasVotes = !!tally && tally.total > 0
    if (!hasVotes && !includeUnvoted && !useMsDefaults) continue

    const severity = hasVotes
      ? tally!.consensusEnabled
        ? tally!.consensusSeverity
        : 'none'
      : useMsDefaults
        ? rule.defaultSeverity
        : 'none'

    entries.push({ entry: { rule, severity }, hasVotes })
  }

  if (useMsDefaults) {
    // Split voted rules from those falling back to Microsoft defaults.
    const voted = entries.filter((e) => e.hasVotes).map((e) => e.entry)
    const defaulted = entries.filter((e) => !e.hasVotes).map((e) => e.entry)

    if (voted.length) {
      lines.push('')
      lines.push('# ##################################################')
      lines.push('# Group votes')
      lines.push('# ##################################################')
      emitByCategory(lines, voted, (l) => `# ===== ${l} =====`, useMsDefaults, optionConsensus)
    }

    lines.push('')
    lines.push('# ##################################################')
    lines.push('# Microsoft defaults (no group vote yet)')
    lines.push('# ##################################################')
    emitByCategory(lines, defaulted, (l) => `# ===== ${l} =====`, useMsDefaults, optionConsensus)
  } else {
    emitByCategory(
      lines,
      entries.map((e) => e.entry),
      (l) => `# ===== ${l} =====`,
      useMsDefaults,
      optionConsensus,
    )
  }

  lines.push('')
  return lines.join('\n')
}
